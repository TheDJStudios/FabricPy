"""Editor types for FabricPy's compile-time callback context.

These protocols describe the portable authoring API; they are not runtime
Minecraft objects and must not be instantiated. Callback bodies are transpiled.
"""
from __future__ import annotations

from typing import Protocol


class BlockPosition(Protocol):
    """Opaque Java block position with the common accessor methods."""
    def getX(self, /) -> int: ...
    def getY(self, /) -> int: ...
    def getZ(self, /) -> int: ...


class Vector3(Protocol):
    x: float
    y: float
    z: float


class Player(Protocol):
    def send_message(self, text: str, /) -> None: ...
    def send_action_bar(self, text: str, /) -> None: ...
    def teleport(self, x: float, y: float, z: float, /) -> None: ...
    def teleport_dimension(self, dimension_id: str, x: float, y: float, z: float, /) -> int: ...
    def give_item(self, item_id: str, count: int, /) -> bool: ...
    def remove_item(self, item_id: str, count: int, /) -> int: ...
    def get_health(self, /) -> float: ...
    def set_health(self, value: float, /) -> None: ...
    def heal(self, amount: float, /) -> None: ...
    def damage(self, amount: float, /) -> bool: ...
    def add_effect(self, effect_id: str, seconds: int, amplifier: int, /) -> bool: ...
    def remove_effect(self, effect_id: str, /) -> bool: ...
    def clear_effects(self, /) -> bool: ...
    def get_hunger(self, /) -> int: ...
    def set_hunger(self, value: int, /) -> None: ...
    def get_saturation(self, /) -> float: ...
    def set_saturation(self, value: float, /) -> None: ...
    def add_experience(self, amount: int, /) -> None: ...
    def kill(self, /) -> None: ...
    def get_name(self, /) -> str: ...
    def is_creative(self, /) -> bool: ...
    def is_sneaking(self, /) -> bool: ...
    def is_sprinting(self, /) -> bool: ...
    def set_on_fire(self, seconds: int, /) -> None: ...
    def get_pos_x(self, /) -> float: ...
    def get_pos_y(self, /) -> float: ...
    def get_pos_z(self, /) -> float: ...
    def get_main_hand_item_id(self, /) -> str: ...
    def get_main_hand_count(self, /) -> int: ...
    def get_offhand_item_id(self, /) -> str: ...
    def get_offhand_count(self, /) -> int: ...
    def consume_main_hand_item(self, count: int, /) -> None: ...
    def set_main_hand_item(self, item_id: str, count: int, /) -> None: ...
    def has_item(self, item_id: str, /) -> bool: ...
    def count_item(self, item_id: str, /) -> int: ...
    def has_advancement(self, advancement_id: str, /) -> bool: ...
    def has_advancment(self, advancement_id: str, /) -> bool: ...
    def add_cooldown(self, item_id: str, ticks: int, /) -> None: ...


class World(Protocol):
    def is_client(self, /) -> bool: ...
    def play_sound(self, sound_id: str, volume: float, pitch: float, /) -> None: ...
    def explode(self, x: float, y: float, z: float, power: float, /) -> object: ...
    def set_block(self, x: int, y: int, z: int, block_id: str, /) -> bool: ...
    def break_block(self, x: int, y: int, z: int, drop: bool, /) -> bool: ...
    def get_block_id(self, x: int, y: int, z: int, /) -> str: ...
    def is_air(self, x: int, y: int, z: int, /) -> bool: ...
    def get_time(self, /) -> int: ...
    def is_day(self, /) -> bool: ...
    def is_raining(self, /) -> bool: ...
    def get_dimension(self, /) -> str: ...
    def spawn_entity(self, entity_id: str, x: float, y: float, z: float, /) -> int: ...
    def set_block_in_dimension(self, dimension_id: str, x: int, y: int, z: int, block_id: str, /) -> int: ...
    def fill_in_dimension(self, dimension_id: str, x1: int, y1: int, z1: int, x2: int, y2: int, z2: int, block_id: str, mode: str | None, /) -> int: ...
    def place_structure(self, dimension_id: str, structure_id: str, x: int, y: int, z: int, /) -> int: ...
    def place_nbt(self, dimension_id: str, structure_id: str, x: int, y: int, z: int, /) -> int: ...
    def spawn_particle(self, particle_id: str, x: float, y: float, z: float, dx: float, dy: float, dz: float, speed: float, count: int, /) -> None: ...
    def raycast_block(self, start_vec: Vector3, end_vec: Vector3, /) -> object: ...
    def raycast_block_id(self, start_vec: Vector3, end_vec: Vector3, /) -> str: ...
    def raycast_block_pos_x(self, start_vec: Vector3, end_vec: Vector3, /) -> int: ...
    def raycast_block_pos_y(self, start_vec: Vector3, end_vec: Vector3, /) -> int: ...
    def raycast_block_pos_z(self, start_vec: Vector3, end_vec: Vector3, /) -> int: ...


class PositionedWorld(World, Protocol):
    """World operations requiring the block/entity callback's current position."""
    def set_block_self(self, block_id: str, /) -> bool: ...
    def break_self(self, drop: bool, /) -> bool: ...
    def get_self_block_id(self, /) -> str: ...
    def is_self_air(self, /) -> bool: ...
    def spawn_particle_self(self, particle_id: str, dx: float, dy: float, dz: float, speed: float, count: int, /) -> None: ...


class Hand(Protocol):
    def is_main_hand(self, /) -> bool: ...
    def is_off_hand(self, /) -> bool: ...


class ItemData(Protocol):
    """Persistent values on this actual stack; keys are independent of storage slots."""
    def get_string(self, key: str, /) -> str: ...
    def set_string(self, key: str, value: str, /) -> None: ...
    def get_int(self, key: str, /) -> int: ...
    def set_int(self, key: str, value: int, /) -> None: ...
    def get_bool(self, key: str, /) -> bool: ...
    def set_bool(self, key: str, value: bool, /) -> None: ...
    def get_float(self, key: str, /) -> float: ...
    def set_float(self, key: str, value: float, /) -> None: ...
    def contains(self, key: str, /) -> bool: ...
    def remove(self, key: str, /) -> None: ...


class ItemInventory(Protocol):
    """Fixed-slot storage; transfers move real items rather than creating copies."""
    def size(self, /) -> int: ...
    def get_item_id(self, slot: int, /) -> str: ...
    def get_count(self, slot: int, /) -> int: ...
    def count(self, item_id: str, /) -> int: ...
    def contains(self, item_id: str, count: int, /) -> bool: ...
    def space(self, item_id: str, /) -> int: ...
    def insert_from_hand(self, hand_name: str, count: int, /) -> int: ...
    def extract_to_player(self, slot: int, count: int, /) -> int: ...
    def open(self, /) -> bool: ...


class ItemAttachments(Protocol):
    """One real item in each configured named slot."""
    def get_item_id(self, name: str, /) -> str: ...
    def has(self, name: str, /) -> bool: ...
    def install_from_hand(self, name: str, hand_name: str, /) -> bool: ...
    def remove_to_player(self, name: str, /) -> bool: ...


class ItemStack(Protocol):
    data: ItemData
    inventory: ItemInventory
    attachments: ItemAttachments
    def get_item_id(self, /) -> str: ...
    def get_count(self, /) -> int: ...
    def decrement(self, count: int, /) -> None: ...
    def increment(self, count: int, /) -> None: ...
    def is_of(self, item_id: str, /) -> bool: ...
    def get_texture(self, /) -> str: ...
    def texture_change(self, texture_id: str, /) -> None: ...
    def get_model(self, /) -> str: ...
    def model_change(self, model_id: str, /) -> None: ...


class BlockEntity(Protocol):
    """Data methods require persistent block data; animation methods require geo assets."""
    def mark_dirty(self, /) -> None: ...
    def get_string(self, key: str, /) -> str: ...
    def set_string(self, key: str, value: str, /) -> None: ...
    def get_int(self, key: str, /) -> int: ...
    def set_int(self, key: str, value: int, /) -> None: ...
    def get_bool(self, key: str, /) -> bool: ...
    def set_bool(self, key: str, value: bool, /) -> None: ...
    def get_double(self, key: str, /) -> float: ...
    def set_double(self, key: str, value: float, /) -> None: ...
    def has(self, key: str, /) -> bool: ...
    def remove(self, key: str, /) -> None: ...
    def sync(self, /) -> None: ...
    def get_texture(self, /) -> str: ...
    def texture_change(self, texture_id: str, /) -> None: ...
    def get_model(self, /) -> str: ...
    def model_change(self, model_id: str, /) -> None: ...
    def get_animation(self, /) -> str: ...
    def play_animation(self, name: str, /) -> None: ...
    def play_animation_once(self, name: str, /) -> None: ...
    def stop_animation(self, /) -> None: ...


class Entity(Protocol):
    def get_pos_x(self, /) -> float: ...
    def get_pos_y(self, /) -> float: ...
    def get_pos_z(self, /) -> float: ...
    def teleport(self, x: float, y: float, z: float, /) -> None: ...
    def discard(self, /) -> None: ...
    def set_on_fire(self, seconds: int, /) -> None: ...
    def damage(self, amount: float, /) -> bool: ...
    def get_animation(self, /) -> str: ...
    def play_animation(self, name: str, /) -> None: ...
    def play_animation_once(self, name: str, /) -> None: ...
    def stop_animation(self, /) -> None: ...
    def get_texture(self, /) -> str: ...
    def texture_change(self, resource_id: str, /) -> None: ...
    def get_model(self, /) -> str: ...
    def model_change(self, resource_id: str, /) -> None: ...


class Math(Protocol):
    def vec3(self, x: float, y: float, z: float, /) -> Vector3: ...
    def block_pos(self, x: int, y: int, z: int, /) -> BlockPosition: ...
    def clamp(self, value: float, min: float, max: float, /) -> float: ...
    def lerp(self, start: float, end: float, delta: float, /) -> float: ...
    def distance3(self, x1: float, y1: float, z1: float, x2: float, y2: float, z2: float, /) -> float: ...
    def length3(self, x: float, y: float, z: float, /) -> float: ...
    def normalize3(self, x: float, y: float, z: float, /) -> Vector3: ...
    def add3(self, x1: float, y1: float, z1: float, x2: float, y2: float, z2: float, /) -> Vector3: ...


class Client(Protocol):
    """Client panel helpers; call from a client-side callback."""
    def open_screen(self, screen_id: str, /) -> None: ...
    def close_screen(self, /) -> None: ...


class BlockContext(Protocol):
    world: PositionedWorld
    pos: BlockPosition
    state: object
    math: Math


class BlockUseContext(BlockContext, Protocol):
    client: Client
    player: Player
    hand: Hand
    stack: ItemStack


class BlockPlaceContext(BlockContext, Protocol):
    player: Player | None


class BlockBreakContext(BlockContext, Protocol):
    player: Player


class BlockEntityUseContext(BlockUseContext, Protocol):
    block_entity: BlockEntity


class BlockEntityPlaceContext(BlockPlaceContext, Protocol):
    block_entity: BlockEntity


class BlockEntityBreakContext(BlockBreakContext, Protocol):
    block_entity: BlockEntity


class ItemUseContext(Protocol):
    client: Client
    player: Player
    world: World
    hand: Hand
    stack: ItemStack
    math: Math


class BlockTickContext(BlockContext, Protocol):
    block_entity: BlockEntity


class EntityTickContext(Protocol):
    entity: Entity
    world: PositionedWorld
    pos: BlockPosition
    math: Math
